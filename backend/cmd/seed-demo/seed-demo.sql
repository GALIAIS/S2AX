-- 14 days x 5 users x 3 models = 210 usage rows with varied tokens, costs, endpoints and mappings.
WITH demo_users AS (
    SELECT u.id,
           u.email,
           k.id AS api_key_id,
           ROW_NUMBER() OVER (ORDER BY u.email)::int - 1 AS user_idx
    FROM users AS u
    JOIN api_keys AS k ON k.user_id = u.id
                       AND k.key LIKE 'sk-demo-%'
                       AND k.deleted_at IS NULL
    WHERE u.email LIKE 'demo.%@sub2api.local'
      AND u.deleted_at IS NULL
), model_definitions(model_name, upstream_model, group_name, account_name, inbound_endpoint, upstream_endpoint, model_idx, input_rate, output_rate) AS (
    VALUES
        ('claude-sonnet-4-6', 'claude-sonnet-4-6-20250514', 'demo-claude', '[DEMO] Anthropic pool', '/v1/messages', '/v1/messages', 0, 3.00::numeric, 15.00::numeric),
        ('gpt-4.1', 'gpt-4.1', 'demo-openai', '[DEMO] OpenAI pool', '/v1/chat/completions', '/v1/chat/completions', 1, 2.00::numeric, 8.00::numeric),
        ('gemini-2.5-pro', 'gemini-2.5-pro-preview-05-06', 'demo-gemini', '[DEMO] Gemini pool', '/v1beta/models', '/v1beta/models', 2, 1.25::numeric, 10.00::numeric)
), seed_base AS (
    SELECT
        format('demo-seed-%s-%s-%s', d.day_idx, u.user_idx, m.model_idx) AS request_id,
        u.id AS user_id,
        u.api_key_id,
        a.id AS account_id,
        g.id AS group_id,
        m.model_name,
        m.upstream_model,
        m.inbound_endpoint,
        m.upstream_endpoint,
        m.model_idx,
        d.day_idx,
        (CURRENT_DATE - d.day_idx)::timestamptz
            + CASE
                WHEN d.day_idx = 0 THEN
                    -((5 + u.user_idx * 7 + m.model_idx * 4) * INTERVAL '1 minute')
                ELSE
                    ((8 + ((u.user_idx * 3 + m.model_idx * 2 + d.day_idx) % 10)) * INTERVAL '1 hour')
                    + ((u.user_idx * 11 + m.model_idx * 17 + d.day_idx * 3) % 50) * INTERVAL '1 minute'
              END AS created_at,
        (1900 + d.day_idx * 85 + u.user_idx * 170 + m.model_idx * 260) AS input_tokens,
        (520 + (d.day_idx % 5) * 80 + u.user_idx * 45 + m.model_idx * 95) AS output_tokens,
        (120 + ((d.day_idx + u.user_idx) % 4) * 90) AS cache_creation_tokens,
        (260 + ((d.day_idx + m.model_idx) % 5) * 140) AS cache_read_tokens,
        m.input_rate,
        m.output_rate,
        g.rate_multiplier,
        (d.day_idx + u.user_idx + m.model_idx) % 2 = 0 AS is_stream
    FROM demo_users AS u
    CROSS JOIN model_definitions AS m
    CROSS JOIN generate_series(0, 13) AS d(day_idx)
    JOIN groups AS g ON g.name = m.group_name AND g.deleted_at IS NULL
    JOIN accounts AS a ON a.name = m.account_name AND a.deleted_at IS NULL
), priced AS (
    SELECT *,
           ROUND((input_tokens * input_rate / 1000000.0)::numeric, 10) AS input_cost,
           ROUND((output_tokens * output_rate / 1000000.0)::numeric, 10) AS output_cost,
           ROUND((cache_creation_tokens * input_rate * 1.10 / 1000000.0)::numeric, 10) AS cache_creation_cost,
           ROUND((cache_read_tokens * input_rate * 0.10 / 1000000.0)::numeric, 10) AS cache_read_cost
    FROM seed_base
), totals AS (
    SELECT *,
           ROUND((input_cost + output_cost + cache_creation_cost + cache_read_cost)::numeric, 10) AS total_cost
    FROM priced
)
