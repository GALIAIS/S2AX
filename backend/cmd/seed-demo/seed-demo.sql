WITH hourly AS (
    SELECT DATE_TRUNC('hour', ul.created_at AT TIME ZONE CURRENT_SETTING('TIMEZONE')) AT TIME ZONE CURRENT_SETTING('TIMEZONE') AS bucket_start,
           COUNT(*) AS total_requests,
           COALESCE(SUM(ul.input_tokens), 0) AS input_tokens,
           COALESCE(SUM(ul.output_tokens), 0) AS output_tokens,
           COALESCE(SUM(ul.cache_creation_tokens), 0) AS cache_creation_tokens,
           COALESCE(SUM(ul.cache_read_tokens), 0) AS cache_read_tokens,
           COALESCE(SUM(ul.total_cost), 0) AS total_cost,
           COALESCE(SUM(ul.actual_cost), 0) AS actual_cost,
           COALESCE(SUM(COALESCE(ul.account_stats_cost, ul.total_cost) * COALESCE(ul.account_rate_multiplier, 1)), 0) AS account_cost,
           COALESCE(SUM(COALESCE(ul.duration_ms, 0)), 0) AS total_duration_ms
    FROM usage_logs AS ul
    WHERE ul.created_at >= NOW() - INTERVAL '15 days'
    GROUP BY 1
), active_users AS (
    SELECT hu.bucket_start, COUNT(*) AS active_users
    FROM usage_dashboard_hourly_users AS hu
    WHERE hu.bucket_start >= DATE_TRUNC('hour', NOW() - INTERVAL '15 days')
    GROUP BY hu.bucket_start
)
